#!/usr/bin/env python3
"""JEG-1348: extract only the approved, counted O3 rows from the committed matrix.

No new research or engine run. Use --check to verify the shipped static asset.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
MATRIX = ROOT / "docs/research/bench-decay-evidence/output/evidence_matrix.json"
ASSET = ROOT / "app/v2/bench-breakout-evidence.js"


def build(raw):
    matrix = json.loads(raw)
    rows = []
    for pos in ("QB", "RB", "WR", "TE"):
        for depth in (1, 2, 3):
            rid = f"O3.{pos}.d{depth}"
            matches = [r for r in matrix["rows"] if r["id"] == rid]
            if len(matches) != 1:
                raise ValueError(f"Expected one {rid}")
            row = matches[0]
            n, count, rate = row["n"], row["values"]["breakouts"], row["values"]["rate"]
            if (row["evidence"] != "historical" or row["window"] != "measured from week 9"
                    or row["source"] != "post1_breakout_rate"
                    or type(n) is not int or n <= 0 or type(count) is not int
                    or not 0 <= count <= n or type(rate) not in (int, float)
                    or not 0 <= rate <= 1 or abs(rate - count / n) > 0.000051):
                raise ValueError(f"Invalid counted historical evidence: {rid}")
            rows.append({"id": rid, "position": pos, "depth": depth, "n": n,
                         "breakouts": count, "rate": rate})
    return {"schema": "bench-breakout-evidence/1", "evidence": "historical",
            "matrix": str(MATRIX.relative_to(ROOT)), "matrixSha256": hashlib.sha256(raw).hexdigest(),
            "asOf": matrix["as_of"], "measureWeek": 9, "seasons": "2015–2025", "teams": 12,
            "basis": "Half-PPR points per game; starter tiers QB 12, RB 24, WR 36, TE 12. "
                     "Backup depths are groups of 12 players below those tiers at week 9. "
                     "A breakout reached the starter tier by full-season points per game. "
                     "Historical reference, not a forecast for your players or selected week. "
                     "The source falls back to standard scoring or zero when half-PPR is missing.",
            "rows": rows}


def output(raw):
    return ("// Generated by tools/research/bench-decay-evidence/build_readout_asset.py; do not edit.\n"
            + "window.TradeValueBenchEvidence = " + json.dumps(build(raw), ensure_ascii=False, separators=(",", ":")) + ";\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = output(MATRIX.read_bytes())
    if args.check:
        if not ASSET.exists() or ASSET.read_text() != expected:
            raise SystemExit("bench breakout evidence asset is stale")
        print("bench breakout evidence asset matches committed O3 matrix")
    else:
        ASSET.write_text(expected)
