"""Figures page for JEG-1336 from tools/research/jeg1336_fill_in.py output.

Usage:
  python3 tools/research/jeg1336_report.py docs/research/data/jeg1336_fill_in.json \
      > docs/research/data/jeg1336_fill_in.md
"""
from __future__ import annotations

import json
import statistics
import sys

OPTS = ("A", "B", "C", "D", "BD")


def f2(x):
    return "" if x is None else f"{x:.2f}"


def names(xs):
    """Players gone from the later bake's naming table show as a key."""
    shown = [x for x in xs if not str(x).isdigit()]
    gone = len(xs) - len(shown)
    return ", ".join(shown + ([f"{gone} no longer named"] if gone else [])) or "-"


def pct(xs, q):
    if not xs:
        return None
    xs = sorted(xs)
    return xs[min(len(xs) - 1, int(q * len(xs)))]


def main(path):
    r = json.load(open(path))
    out = ["# JEG-1336 figures: chart fill-in membership (VP-2.4)", "",
           f"Generated by `tools/research/jeg1336_report.py` from `jeg1336_fill_in.py` at "
           f"`{r['repo_head'][:8]}`. {r['hook_check']}. Option B uses σ {r['sigma']} PPG. "
           "DDF Value throughout. The allocation is held wherever a step is measured, so flex and "
           "bench flips (JEG-1286) are not counted.", ""]

    # 1. Fill boundary
    out += ["## 1. Today's RB fill boundary", "",
            "The players either side of the last fill-set place. `listed by` = charts in I that list "
            "him; an empty list means every chart estimates him by the curve path.", ""]
    for c in r["today"]:
        if c["cell"] not in ("standard/12", "standard/14", "half_ppr/14"):
            continue
        b = c["boundary"]["RB"]
        out += [f"**{c['cell']}** (fill set {b['fill_size']} RBs)", "",
                "| Rank | Player | Mean PPG | In fill set | Listed by | " + " | ".join(OPTS) + " |",
                "|---|---|---|---|---|" + "---|" * len(OPTS)]
        for x in b["rows"]:
            out.append(f"| {x['rank']} | {x['who']} | {x['mean_ppg']:.2f} | {'yes' if x['in_fill'] else 'no'} | "
                       f"{', '.join(x['listed_by']) or 'none'} | " + " | ".join(f2(x[o]) for o in OPTS) + " |")
        out.append("")

    # 2. Curve-path estimates
    out += ["## 2. Curve-path estimates worth something today", "",
            "Chart estimates for players no chart lists (VP-2.4e) whose Adjusted value is over 0.5, under A.", "",
            "| Setting | Curve estimates | Over 0.5 Adjusted | Largest (chart, player, Adjusted, DDF Value) |",
            "|---|---|---|---|"]
    for c in r["today"]:
        big = sorted((x for x in c["curve"] if (x["adj"] or 0) > 0.5), key=lambda x: -x["adj"])
        top = f"{big[0]['chart']} {big[0]['pos']}, {big[0]['who']}, {big[0]['adj']:.2f}, {big[0]['ddf']:.2f}" if big else ""
        charts = sorted({x["chart"] for x in big})
        out.append(f"| {c['cell']} | {len(c['curve'])} | {len(big)} ({', '.join(charts) or '-'}) | {top} |")
    out.append("")

    # 3. Sweep
    out += ["## 3. One-player sweep near the fill cutoff (allocation held)", "",
            "±0.5 and ±1 PPG to one projection for each player within 3 places of a fill cutoff, at every "
            "position. Largest DDF Value move of any other player.", ""]
    allc = [x for c in r["sweep"] for x in c["cases"]]
    out += ["| Option | Cases | Worst | 99th pct | Over 1.0 | Over 0.5 | Worst case |", "|---|---|---|---|---|---|---|"]
    for o in OPTS:
        mv = [x["options"][o]["ddf"] for x in allc]
        w = max(allc, key=lambda x: x["options"][o]["ddf"]) if allc else None
        wc = (f"{w['options'][o]['who']} {f2(w['options'][o]['before'])} to {f2(w['options'][o]['after'])} "
              f"({w['name']} {w['src']} {w['delta']:+.1f})") if w and w["options"][o]["who"] else ""
        out.append(f"| {o} | {len(mv)} | {f2(max(mv) if mv else None)} | {f2(pct(mv, .99))} | "
                   f"{sum(v > 1.0 for v in mv)} | {sum(v > 0.5 for v in mv)} | {wc} |")
    out += ["", "By setting (worst move):", "", "| Setting | Cases | Fill set changed (A) | " + " | ".join(OPTS) + " |",
            "|---|---|---|" + "---|" * len(OPTS)]
    for c in r["sweep"]:
        cs = c["cases"]
        if not cs:
            continue
        out.append(f"| {c['cell']} | {len(cs)} | {sum(1 for x in cs if x.get('fill_changed'))} | "
                   + " | ".join(f2(max(x["options"][o]["ddf"] for x in cs)) for o in OPTS) + " |")
    out.append("")

    # 4. History
    out += ["## 4. Real updates: fill-set changes between consecutive bakes", "",
            "Every `players.json` bake on main with all three projections, replayed with today's code. A step "
            "is the largest DDF Value gap, at the later bake, between the fill set free and the earlier bake's "
            "fill set held (allocation held to the earlier bake in both). Players with no projection in the "
            "earlier bake follow today's rule in both runs, so only players projected in both bakes count. "
            "Under C the set only changes when a chart adds or drops a player, so C's steps are listing "
            "changes, not cutoff crossings.", "",
            "| Setting | Pairs | Fill set changed | A player no chart lists entered | Step over 0.5 (A) | "
            "Median step when changed (A) | Worst A | " + " | ".join(f"Worst {o}" for o in OPTS[1:]) + " |",
            "|---|---|---|---|---|---|---|" + "---|" * (len(OPTS) - 1)]
    tot = {"pairs": 0, "changed": 0, "none": 0, "over": 0}
    steps_all = {o: [] for o in OPTS}
    worst_rows = []
    for c in r["history"]:
        pairs = [b for b in c["bakes"] if "step" in b]
        changed = [b for b in pairs if any(v["in"] or v["out"] for v in b["changes"].values())]
        none_in = [b for b in pairs if any(v["in_listed_by_none"] for v in b["changes"].values())]
        st = [b["step"]["A"]["ddf"] for b in changed]
        for o in OPTS:
            steps_all[o] += [b["step"][o]["ddf"] for b in pairs]
        over = sum(v > 0.5 for v in st)
        tot["pairs"] += len(pairs)
        tot["changed"] += len(changed)
        tot["none"] += len(none_in)
        tot["over"] += over
        wa = max(pairs, key=lambda b: b["step"]["A"]["ddf"]) if pairs else None
        if wa and wa["step"]["A"]["who"]:
            worst_rows.append((wa["step"]["A"]["ddf"], c["cell"], wa))
        out.append(f"| {c['cell']} | {len(pairs)} | {len(changed)} | {len(none_in)} | {over} | "
                   f"{f2(statistics.median(st) if st else None)} | "
                   + " | ".join(f2(max((b['step'][o]['ddf'] for b in pairs), default=None)) for o in OPTS) + " |")
    out += ["", f"All settings: {tot['pairs']} pairs, fill set changed in {tot['changed']}, a player no chart "
            f"lists entered in {tot['none']}, step over 0.5 under A in {tot['over']}.", "",
            "| Option | Steps over 0.5 | Steps over 1.0 | Worst |", "|---|---|---|---|"]
    for o in OPTS:
        s = steps_all[o]
        out.append(f"| {o} | {sum(v > 0.5 for v in s)} | {sum(v > 1.0 for v in s)} | {f2(max(s) if s else None)} |")
    out += ["", "Largest steps per option (projected rank now / before / fill-set size):", ""]
    for o in OPTS:
        big = sorted(((b["step"][o]["ddf"], c["cell"], b) for c in r["history"] for b in c["bakes"]
                      if "step" in b and b["step"][o]["who"]), key=lambda t: -t[0])[:5]
        out.append(f"- {o}: " + "; ".join(
            f"{cell} {b['when'][:10]} {b['step'][o]['who']} {f2(b['step'][o]['held'])} to {f2(b['step'][o]['free'])} "
            f"(rank {b['step'][o]['rank']} / {b['step'][o]['prev_rank']} / {b['step'][o]['cutoff']})"
            for _, cell, b in big))
    out += ["", "Largest A step per setting:", "", "| Setting | Bake | Player | Held to free (A) | Entered / left the RB fill set |",
            "|---|---|---|---|---|"]
    for w, cell, b in sorted(worst_rows, reverse=True):
        rb = b["changes"]["RB"]
        out.append(f"| {cell} | {b['when'][:10]} {b['sha']} | {b['step']['A']['who']} | "
                   f"{f2(b['step']['A']['held'])} to {f2(b['step']['A']['free'])} | "
                   f"in: {names(rb['in'])}; out: {names(rb['out'])} |")
    out.append("")

    # 5. One-time change
    out += ["## 5. One-time change from today's values", "",
            "| Setting | " + " | ".join(f"{o} worst" for o in OPTS[1:]) + " | " + " | ".join(f"{o} moved >0.1" for o in OPTS[1:]) + " |",
            "|---|" + "---|" * (2 * (len(OPTS) - 1))]
    for c in r["today"]:
        d = c["departure"]
        out.append(f"| {c['cell']} | " + " | ".join(f"{f2(d[o]['worst'])} {d[o]['worst_who'] or ''}" for o in OPTS[1:])
                   + " | " + " | ".join(str(d[o]["moved_over_0.1"]) for o in OPTS[1:]) + " |")
    out += ["", "Largest movers, standard/12, USO and Charlotte:", ""]
    for c in r["today"]:
        if c["cell"] not in ("standard/12", "uso", "charlotte"):
            continue
        for o in OPTS[1:]:
            t = c["departure"][o]["top"]
            out.append(f"- {c['cell']} {o}: " + "; ".join(f"{x['who']} {x['before']:.2f} to {x['after']:.2f}" for x in t))
    out.append("")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
